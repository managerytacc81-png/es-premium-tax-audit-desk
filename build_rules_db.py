def build_states_json(output_path: Path):
    assert len(STATES_DATA) == 51, f"Expected 51 jurisdictions, got {len(STATES_DATA)}"
    
    # Validation checks
    stamping_states = [s for s, d in STATES_DATA.items() if d["stamping_office"]]
    assert len(stamping_states) == 15, f"Expected 15 stamping states, got {len(stamping_states)}: {stamping_states}"
    expected_15 = {"AZ", "CA", "FL", "ID", "IL", "MN", "MS", "NV", "NY", "NC", "OR", "PA", "TX", "UT", "WA"}
    assert set(stamping_states) == expected_15, f"Stamping states mismatch: {set(stamping_states) ^ expected_15}"
    
    for code, data in STATES_DATA.items():
        assert data["tax_rate"] >= 0.925 and data["tax_rate"] <= 6.0, f"Rate out of bounds for {code}: {data['tax_rate']}"
        assert data["direct_procurement_tax_rate"] > 0, f"Missing direct procurement rate for {code}"
        assert "sources" in data and len(data["sources"]) == 3, f"Missing complete citations for {code}"
        assert data["statutory_cite"], f"Missing statutory cite for {code}"
        assert data["return_premium_credit_mechanics"] in {"cash-refund", "credit-only", "amended-return", "negative-endorsement", "annual-reconciliation"}

    output_path.parent.mkdir(parents=True, exist_ok=True)
    with open(output_path, "w", encoding="utf-8") as f:
        json.dump(STATES_DATA, f, indent=2, sort_keys=True)
    print(f"Successfully wrote {len(STATES_DATA)} jurisdictions to {output_path}")

